"""PostgreSQL connection adapter for the terminal's persistent application data.

The adapter keeps the existing small execute/fetchone call surface while all
storage is backed by PostgreSQL. DATABASE_URL must be a server-side secret.
DATABASE_SCHEMA defaults to the private, non-Data-API-exposed "app" schema.
"""
from __future__ import annotations

import os
import re
from typing import Any

import psycopg
from psycopg.rows import tuple_row

_SCHEMA_RE = re.compile(r"^[a-z_][a-z0-9_]{0,62}$")
_ID_TABLES = {"trades", "monitoring_events", "thesis_reassessments"}


class Row(dict):
    """Mapping row with sqlite-style numeric indexing for legacy callers."""
    def __getitem__(self, key: Any) -> Any:
        if isinstance(key, int):
            return tuple(self.values())[key]
        return super().__getitem__(key)


class Cursor:
    def __init__(self, cursor, buffered=None):
        self._cursor = cursor
        self._buffered = buffered
        self.lastrowid = buffered[0] if buffered is not None and buffered else None

    @property
    def rowcount(self):
        return self._cursor.rowcount

    def _row(self, value):
        if value is None:
            return None
        return Row((column.name, item) for column, item in zip(self._cursor.description, value))

    def fetchone(self):
        if self._buffered is not None:
            value, self._buffered = self._buffered, None
            return self._row(value)
        return self._row(self._cursor.fetchone())

    def fetchall(self):
        rows = []
        if self._buffered is not None:
            rows.append(self._buffered)
            self._buffered = None
        rows.extend(self._cursor.fetchall())
        return [self._row(value) for value in rows]


class Connection:
    def __init__(self, raw):
        self._raw = raw
        self.row_factory = None  # Compatibility with the former sqlite call sites.

    def execute(self, sql: str, params=()):
        statement = sql.strip()
        if statement.upper().startswith("PRAGMA "):
            return Cursor(self._raw.cursor())
        if statement.upper() == "BEGIN IMMEDIATE":
            cur = self._raw.execute("SELECT pg_advisory_xact_lock(781246190)")
            return Cursor(cur)
        statement = re.sub(r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b",
                            "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", statement, flags=re.I)
        statement = re.sub(r"\bINTEGER\s+PRIMARY\s+KEY\b",
                            "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", statement, flags=re.I)
        statement = statement.replace("INSERT OR IGNORE INTO", "INSERT INTO")
        if "INSERT INTO" in statement.upper() and "ON CONFLICT" not in statement.upper() and sql.upper().find("INSERT OR IGNORE") >= 0:
            statement = statement.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
        statement = statement.replace("?", "%s")
        table_match = re.search(r"INSERT\s+INTO\s+([a-z_][a-z0-9_]*)", statement, re.I)
        add_returning = bool(table_match and table_match.group(1).lower() in _ID_TABLES and "RETURNING" not in statement.upper())
        if add_returning:
            statement = statement.rstrip().rstrip(";") + " RETURNING id"
        cur = self._raw.execute(statement, params or ())
        buffered = None
        if add_returning and cur.description is not None:
            buffered = cur.fetchone()
        return Cursor(cur, buffered)

    def commit(self):
        self._raw.commit()

    def rollback(self):
        self._raw.rollback()

    def close(self):
        self._raw.close()

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        if exc_type is None:
            self.commit()
        else:
            self.rollback()
        self.close()
        return False


def connect() -> Connection:
    url = os.getenv("DATABASE_URL", "").strip()
    if not url:
        raise RuntimeError("DATABASE_URL is required. Configure the Supabase PostgreSQL connection string on the backend.")
    schema = os.getenv("DATABASE_SCHEMA", "app").strip()
    if not _SCHEMA_RE.fullmatch(schema):
        raise RuntimeError("DATABASE_SCHEMA must be a simple PostgreSQL schema identifier.")
    raw = psycopg.connect(url, row_factory=tuple_row)
    try:
        raw.execute(f'CREATE SCHEMA IF NOT EXISTS "{schema}"')
        raw.execute(f'SET search_path TO "{schema}", public')
        raw.commit()
    except Exception:
        raw.close()
        raise
    return Connection(raw)
